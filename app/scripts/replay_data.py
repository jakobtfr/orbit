"""Export the NASA UTMB bed-rest vitals used by the Replay screen.

Reads data/utmb/daily_vitals.csv and data/utmb/baselines.csv, keeps the in-bed-rest
days (fase == mision) of every subject with a pre-bed-rest baseline, and writes
src/data/utmb-replay.json. Values are copied as they are; no cleaning or filling.

Run from app/:  uv run scripts/replay_data.py
"""

import csv
import json
from collections import defaultdict
from pathlib import Path

APP = Path(__file__).resolve().parent.parent
UTMB = APP.parent / "data" / "utmb"
OUT = APP / "src" / "data" / "utmb-replay.json"


def num(x: str) -> float | None:
    return float(x) if x else None


def main() -> None:
    base = {r["astronauta_id"]: r for r in csv.DictReader(open(UTMB / "baselines.csv"))}
    days = defaultdict(list)
    for r in csv.DictReader(open(UTMB / "daily_vitals.csv")):
        if r["fase"] == "mision":
            days[r["astronauta_id"]].append(r)

    subjects = []
    for sid in sorted(days):
        b = base[sid]
        if not b["pulso_lpm_media"]:
            continue
        rows = sorted(days[sid], key=lambda r: int(r["dia_mision"]))
        subjects.append({
            "id": sid,
            "campaign": rows[0]["campana"],
            "baseline": {
                "days": int(b["n_dias_base"]),
                "hr": num(b["pulso_lpm_media"]),
                "sys": num(b["pas_mmhg_media"]),
                "dia": num(b["pad_mmhg_media"]),
                "temp": num(b["temp_c_media"]),
            },
            # [day, heart rate, systolic, diastolic, temperature]
            "days": [
                [int(r["dia_mision"]), num(r["pulso_lpm"]), num(r["pas_mmhg"]), num(r["pad_mmhg"]), num(r["temp_c"])]
                for r in rows
            ],
        })

    OUT.write_text(json.dumps({
        "note": "In-bed-rest daily vitals and pre-bed-rest baselines from NASA UTMB head-down tilt bed rest, "
                "data/utmb/daily_vitals.csv and baselines.csv (DOI 10.83263/wjw1-ta27). Generated by scripts/replay_data.py.",
        "subjects": subjects,
    }, separators=(",", ":")))
    print(f"{len(subjects)} subjects, {sum(len(s['days']) for s in subjects)} days -> {OUT.relative_to(APP)}")


if __name__ == "__main__":
    main()
